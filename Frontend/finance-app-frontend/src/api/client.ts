import axios, { isAxiosError } from 'axios'
import type { paths } from './schema'

export const API_URL: string = import.meta.env.VITE_API_URL ?? 'http://127.0.0.1:8000'

/** Shared axios instance. Axios serializes `data` to JSON and sets the Content-Type itself. */
export const http = axios.create({ baseURL: API_URL, timeout: 15_000 })

http.interceptors.response.use(undefined, (error: unknown) => {
  // Cancelled requests (e.g. a query whose component unmounted) are expected, not failures
  if (isAxiosError(error) && error.code !== 'ERR_CANCELED') {
    const { method, url } = error.config ?? {}
    console.error(`[api] ${method?.toUpperCase()} ${url} failed:`, error.response?.status ?? error.code, error.response?.data ?? error.message)
  }
  return Promise.reject(error)
})

/* ---------- Types derived from the OpenAPI schema (src/api/schema.d.ts, generated by `npm run gen:api`) ---------- */

type Method = 'get' | 'post'
type Operation<P extends keyof paths, M extends Method> = NonNullable<paths[P][M]>
type PathsWith<M extends Method> = { [P in keyof paths]: paths[P][M] extends { responses: unknown } ? P : never }[keyof paths]

type JsonBody<Op> = Op extends { requestBody: { content: { 'application/json': infer B } } } ? B : never
type JsonResponse<Op> = Op extends { responses: { 200: { content: { 'application/json': infer R } } } } ? R : never
type PathParams<Op> = Op extends { parameters: { path: infer PP } } ? PP : never
type QueryParams<Op> = Op extends { parameters: { query?: infer Q } } ? NonNullable<Q> : never

/** `path` and `body` are required exactly when the endpoint declares them; `query` is accepted when it has any. */
type Options<Op> = { signal?: AbortSignal } & ([PathParams<Op>] extends [never] ? unknown : { path: PathParams<Op> }) &
  ([QueryParams<Op>] extends [never] ? unknown : { query?: QueryParams<Op> }) &
  ([JsonBody<Op>] extends [never] ? unknown : { body: JsonBody<Op> })
type Args<Op> = object extends Options<Op> ? [options?: Options<Op>] : [options: Options<Op>]

function buildUrl(template: string, params?: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params?.[key]
    if (value === undefined) throw new Error(`Missing path parameter "${key}" for ${template}`)
    return encodeURIComponent(String(value))
  })
}

async function request<M extends Method, P extends PathsWith<M>>(
  method: M,
  url: P,
  options: { path?: Record<string, string | number>; query?: object; body?: unknown; signal?: AbortSignal } = {},
): Promise<JsonResponse<Operation<P, M>>> {
  const response = await http.request({
    method,
    url: buildUrl(url, options.path),
    params: options.query,
    data: options.body,
    signal: options.signal,
  })
  return response.data
}

export const get = <P extends PathsWith<'get'>>(url: P, ...[options]: Args<Operation<P, 'get'>>) =>
  request('get', url, options as Parameters<typeof request>[2])

export const post = <P extends PathsWith<'post'>>(url: P, ...[options]: Args<Operation<P, 'post'>>) =>
  request('post', url, options as Parameters<typeof request>[2])
